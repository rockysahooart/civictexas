// Renders an approved AI summary. Shape is defined in summarization/schema.py.
import type { Summary } from "@/lib/bills";
import { formatDateTime } from "@/lib/format";

type Citation = { section: string; quote: string };
type Statement = { text: string; citations: Citation[] };
type Affected = { group: string; effect: string; basis: "stated" | "inferred"; citations: Citation[] };
export type SummaryContent = {
  overview: Statement;
  key_provisions: Statement[];
  changes_to_existing_law: Statement[];
  affected_groups: Affected[];
  effective_dates: Statement[];
  fiscal_information: Statement | null;
  uncertainties: string[];
};

function Cites({ citations }: { citations: Citation[] }) {
  if (!citations?.length) return null;
  return (
    <span className="ml-1 text-xs text-ink-soft">
      ({citations.map((c) => c.section).join(", ")})
    </span>
  );
}

export function SummaryView({ summary }: { summary: Summary }) {
  const c = summary.content as SummaryContent;
  return (
    <article className="space-y-4 rounded border border-rule bg-card p-5" aria-labelledby={`summary-${summary.id}`}>
      <header className="space-y-1">
        <p className="text-xs font-semibold tracking-wider text-sienna uppercase">AI-generated explanation</p>
        <h3 id={`summary-${summary.id}`} className="text-xl">
          Plain-language summary of version {summary.version_code}
        </h3>
        <p className="text-sm text-ink-soft">
          Generated by {summary.provider} {summary.model_id} on {formatDateTime(summary.generated_at)} from the official
          text, then reviewed by a person{summary.reviewed_at ? ` on ${formatDateTime(summary.reviewed_at)}` : ""}. It may
          still contain errors. The official text is the authority.
        </p>
      </header>
      <p>
        {c.overview.text}
        <Cites citations={c.overview.citations} />
      </p>
      {c.key_provisions.length > 0 && (
        <section>
          <h4 className="font-semibold">Key provisions</h4>
          <ul className="ml-5 list-disc">
            {c.key_provisions.map((s, i) => (
              <li key={i}>
                {s.text}
                <Cites citations={s.citations} />
              </li>
            ))}
          </ul>
        </section>
      )}
      {c.affected_groups.length > 0 && (
        <section>
          <h4 className="font-semibold">Who could be affected</h4>
          <ul className="ml-5 list-disc">
            {c.affected_groups.map((g, i) => (
              <li key={i}>
                <strong>{g.group}:</strong> {g.effect}{" "}
                <span className="text-xs font-semibold">{g.basis === "inferred" ? "[Inferred]" : "[Stated in bill]"}</span>
                <Cites citations={g.citations} />
              </li>
            ))}
          </ul>
        </section>
      )}
      {c.uncertainties.length > 0 && (
        <section>
          <h4 className="font-semibold">Uncertainties</h4>
          <ul className="ml-5 list-disc">
            {c.uncertainties.map((u, i) => (
              <li key={i}>{u}</li>
            ))}
          </ul>
        </section>
      )}
    </article>
  );
}
